"""
Train command - Train classifiers from labeled findings.

This command trains the Naive Bayes classifier using labeled training data
generated by the 'generate' command.
"""

from pathlib import Path
from typing import Any

from ._base import (
    NAIVE_BAYES_MODEL,
    save_model,
    tokenize_comment,
    print_header,
    print_separator,
)


def setup_args(subparsers) -> None:
    """Set up command arguments."""
    parser = subparsers.add_parser(
        'train',
        help='Train classifiers from labeled findings'
    )
    parser.add_argument(
        'findings_dir',
        help='Directory with labeled findings (misleading.txt, accurate.txt)'
    )


def run(args: Any) -> None:
    """Execute the train command."""
    from cortical.audits import load_training_files, CommentClassifier
    from cortical.tokenizer import Tokenizer

    print_header("Classifier Training")

    findings_dir = Path(args.findings_dir)

    # Load training data
    training_data = load_training_files(findings_dir)
    if training_data is None:
        print("Error: Training data not found.")
        print(f"Expected files:")
        print(f"  - {findings_dir}/misleading.txt")
        print(f"  - {findings_dir}/accurate.txt")
        print("\nRun 'audit generate' first to create training data.")
        return

    print(f"Loaded {len(training_data.misleading)} misleading examples")
    print(f"Loaded {len(training_data.accurate)} accurate examples")

    if not training_data.misleading or not training_data.accurate:
        print("Error: Need at least one example of each class")
        return

    # Tokenize comments
    tokenizer = Tokenizer()

    all_comments = []
    all_labels = []

    for comment in training_data.misleading:
        tokens = tokenize_comment(comment, tokenizer)
        if tokens:
            all_comments.append(tokens)
            all_labels.append("misleading")

    for comment in training_data.accurate:
        tokens = tokenize_comment(comment, tokenizer)
        if tokens:
            all_comments.append(tokens)
            all_labels.append("accurate")

    print(f"\nTokenized {len(all_comments)} comments for training")

    # Train Naive Bayes classifier
    print("\nTraining Naive Bayes classifier...")
    classifier = CommentClassifier()
    classifier.fit(all_comments, all_labels)

    # Save model
    save_model(classifier, NAIVE_BAYES_MODEL)

    # Show most indicative words
    print("\nMost indicative words for 'misleading':")
    indicative = classifier.most_indicative_words("misleading", top_n=10)
    for word, prob in indicative:
        print(f"  {word}: {prob:.4f}")

    print("\nMost indicative words for 'accurate':")
    indicative = classifier.most_indicative_words("accurate", top_n=10)
    for word, prob in indicative:
        print(f"  {word}: {prob:.4f}")

    print_separator()
    print("Training complete!")
